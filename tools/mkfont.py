# Build an 8x8 code page 437 font (C header) from Daniel Hepper's public-domain font8x8
# (https://github.com/dhepper/font8x8). usage: mkfont.py <font8x8 dir> <out.h>
# Output rows are MSB = leftmost pixel. Glyphs font8x8 lacks get a small box placeholder.
import sys, re, os

src, out = sys.argv[1], sys.argv[2]

def table(name):
    txt = open(os.path.join(src, name + ".h")).read()
    rows = re.findall(r"\{\s*((?:0x[0-9A-Fa-f]{2}\s*,\s*){7}0x[0-9A-Fa-f]{2})\s*\}", txt)
    return [[int(v, 16) for v in r.split(",")] for r in rows]

basic = table("font8x8_basic")      # U+0000..U+007F
latin = table("font8x8_ext_latin")  # U+00A0..U+00FF
box   = table("font8x8_box")        # U+2500..U+257F
block = table("font8x8_block")      # U+2580..U+259F
greek = table("font8x8_greek")      # U+0390..U+03C9
misc  = table("font8x8_misc")

glyph = {}
for i, g in enumerate(basic): glyph[i] = g
for i, g in enumerate(latin): glyph[0xA0 + i] = g
for i, g in enumerate(box):   glyph[0x2500 + i] = g
for i, g in enumerate(block): glyph[0x2580 + i] = g
for i, g in enumerate(greek): glyph[0x390 + i] = g
glyph[0x20A7] = misc[0]; glyph[0x192] = misc[1]; glyph[0x2310] = misc[4]
glyph[0x2264] = misc[5]; glyph[0x2265] = misc[6]

# CP437 0x01-0x1F and 0x7F are pictographs in the PC character ROM
low = [0x0000, 0x263A, 0x263B, 0x2665, 0x2666, 0x2663, 0x2660, 0x2022, 0x25D8, 0x25CB, 0x25D9,
       0x2642, 0x2640, 0x266A, 0x266B, 0x263C, 0x25BA, 0x25C4, 0x2195, 0x203C, 0x00B6, 0x00A7,
       0x25AC, 0x21A8, 0x2191, 0x2193, 0x2192, 0x2190, 0x221F, 0x2194, 0x25B2, 0x25BC]
# a few hand-drawn pictographs (MSB-left), the rest get the placeholder
hand = {
    0x263A: [0x7E,0x81,0xA5,0x81,0xBD,0x99,0x81,0x7E], 0x263B: [0x7E,0xFF,0xDB,0xFF,0xC3,0xE7,0xFF,0x7E],
    0x2665: [0x6C,0xFE,0xFE,0xFE,0x7C,0x38,0x10,0x00], 0x2666: [0x10,0x38,0x7C,0xFE,0x7C,0x38,0x10,0x00],
    0x2663: [0x38,0x7C,0x38,0xFE,0xFE,0x7C,0x38,0x7C], 0x2660: [0x10,0x10,0x38,0x7C,0xFE,0x7C,0x38,0x7C],
    0x2022: [0x00,0x00,0x18,0x3C,0x3C,0x18,0x00,0x00], 0x25BA: [0x80,0xE0,0xF8,0xFE,0xF8,0xE0,0x80,0x00],
    0x25C4: [0x02,0x0E,0x3E,0xFE,0x3E,0x0E,0x02,0x00], 0x2191: [0x18,0x3C,0x7E,0x18,0x18,0x18,0x18,0x00],
    0x2193: [0x18,0x18,0x18,0x18,0x7E,0x3C,0x18,0x00], 0x2192: [0x00,0x18,0x0C,0xFE,0x0C,0x18,0x00,0x00],
    0x2190: [0x00,0x30,0x60,0xFE,0x60,0x30,0x00,0x00], 0x25B2: [0x00,0x18,0x3C,0x7E,0xFF,0xFF,0x00,0x00],
    0x25BC: [0x00,0xFF,0xFF,0x7E,0x3C,0x18,0x00,0x00], 0x266A: [0x3F,0x33,0x3F,0x30,0x30,0x70,0xF0,0xE0],
    0x2302: [0x00,0x10,0x38,0x6C,0xC6,0xC6,0xFE,0x00],
    0x25A0: [0x00,0x00,0x3C,0x3C,0x3C,0x3C,0x00,0x00], 0x2219: [0x00,0x00,0x00,0x18,0x18,0x00,0x00,0x00],
    0x221A: [0x0F,0x0C,0x0C,0x0C,0xEC,0x6C,0x3C,0x1C], 0x2248: [0x00,0x76,0xDC,0x00,0x76,0xDC,0x00,0x00],
    0x2261: [0x00,0xFC,0x00,0xFC,0x00,0xFC,0x00,0x00], 0x221E: [0x00,0x00,0x7E,0xDB,0xDB,0x7E,0x00,0x00],
    0x2229: [0x78,0xCC,0xCC,0xCC,0xCC,0xCC,0xCC,0x00], 0x207F: [0x78,0x6C,0x6C,0x6C,0x00,0x00,0x00,0x00],
    0x25D8: [0xFF,0xFF,0xE7,0xC3,0xC3,0xE7,0xFF,0xFF], 0x25CB: [0x00,0x3C,0x66,0x42,0x42,0x66,0x3C,0x00],
    0x25D9: [0xFF,0xC3,0x99,0xBD,0xBD,0x99,0xC3,0xFF], 0x2195: [0x18,0x3C,0x7E,0x18,0x18,0x7E,0x3C,0x18],
    0x25AC: [0x00,0x00,0x00,0x00,0x7E,0x7E,0x7E,0x00], 0x2194: [0x00,0x24,0x66,0xFF,0x66,0x24,0x00,0x00],
}
def rev(b): return int("{:08b}".format(b)[::-1], 2)   # font8x8 is LSB-left
PLACEHOLDER = [0x00, 0x7E, 0x42, 0x42, 0x42, 0x42, 0x7E, 0x00]

font, missing = [], []
for code in range(256):
    if code < 0x20: u = low[code]
    elif code == 0x7F: u = 0x2302
    else: u = ord(bytes([code]).decode("cp437"))
    if u in hand: g = hand[u]
    elif u in glyph: g = [rev(b) for b in glyph[u]]
    else: g = PLACEHOLDER; missing.append(code)
    if code == 0: g = [0] * 8
    font.append(g)

with open(out, "w") as f:
    f.write("/* 8x8 code page 437 font, MSB = leftmost pixel. Generated by tools/mkfont.py from\n"
            "   font8x8 by Daniel Hepper (public domain). Placeholder box for: %s */\n"
            % (" ".join("%02X" % c for c in missing) or "none"))
    f.write("#pragma once\n#include <stdint.h>\nstatic const uint8_t font_cp437[256][8] = {\n")
    for code, g in enumerate(font):
        f.write("  {%s}, /* %02X */\n" % (",".join("0x%02X" % b for b in g), code))
    f.write("};\n")
print("cp437 font: %d glyphs, %d placeholders" % (256, len(missing)))
